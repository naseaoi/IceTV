const { createHash } = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');
const { runInThisContext } = require('node:vm');
const prettier = require('prettier');
const ts = require('typescript');

const root = path.resolve(__dirname, '..');
const source = path.join(root, 'src/lib/display-text');
function writeChanged(file, content) {
  if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== content)
    fs.writeFileSync(file, content);
}
function transpile(name) {
  return ts.transpileModule(fs.readFileSync(path.join(source, name), 'utf8'), {
    compilerOptions: {
      target: ts.ScriptTarget.ES2020,
      module: ts.ModuleKind.CommonJS,
      esModuleInterop: true,
    },
  }).outputText;
}

async function generateDisplayConverter(
  directory = path.join(root, 'public/display-text'),
  manifest = path.join(source, 'asset.generated.ts'),
) {
  // The builder has only type imports locally; runtime dependencies resolve through this script.
  const builder = { exports: {} };
  runInThisContext(
    `(function (require, module, exports) {${transpile('build.ts')}\n})`,
    { filename: path.join(source, 'build.ts') },
  )(require, builder, builder.exports);
  const { buildDisplayCommon, buildDisplayVariant } = builder.exports;
  const common = buildDisplayCommon();
  const runtime = transpile('compact.ts');
  const assets = {};
  fs.mkdirSync(directory, { recursive: true });
  for (const [language, name] of [
    ['zh-TW', 'tw'],
    ['zh-HK', 'hk'],
  ]) {
    const variant = buildDisplayVariant(language);
    // Same runtime as the server, without OpenCC's per-character trie nodes or unrelated regions.
    const script = `/* OpenCC JS dictionaries: MIT AND Apache-2.0; https://github.com/nk2028/opencc-js */
(function () {
  try {
    if (document.documentElement.lang !== '${language}') return;
    var exports = {};
${runtime}
    globalThis.__ICETV_DISPLAY_CONVERTER__ = exports.createCompactConverter(exports.createCompactCommon(${JSON.stringify(common)}), ${JSON.stringify(variant)});
  } catch (error) {
    console.warn('Display converter unavailable; using original text.');
  }
})();
`;
    const hash = createHash('sha256').update(script).digest('hex').slice(0, 16);
    const fileName = `opencc-${name}-${hash}.js`;
    writeChanged(path.join(directory, fileName), script);
    assets[language] = `/display-text/${fileName}`;
    console.log(
      `Display converter: ${fileName} (${Buffer.byteLength(script)} bytes)`,
    );
  }
  writeChanged(
    manifest,
    await prettier.format(
      `// Generated by scripts/generate-display-converter.js.\nexport const DISPLAY_CONVERTER_SRC = ${JSON.stringify(assets)} as const;\n`,
      {
        ...(await prettier.resolveConfig(
          path.join(source, 'asset.generated.ts'),
        )),
        parser: 'typescript',
      },
    ),
  );
  const current = new Set(
    Object.values(assets).map((src) => path.basename(src)),
  );
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    if (
      entry.isFile() &&
      /^opencc-.*\.js$/.test(entry.name) &&
      !current.has(entry.name)
    ) {
      fs.unlinkSync(path.join(directory, entry.name));
    }
  }
}

module.exports = { generateDisplayConverter };
if (require.main === module) {
  generateDisplayConverter().catch((error) => {
    console.error(error);
    process.exitCode = 1;
  });
}
